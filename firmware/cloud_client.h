/**
 ******************************************************************************
 * @file    cloud_client.h
 * @author  Qinn
 * @brief   声明可选远程调试云端隧道客户端的启动与状态查询接口。
 ******************************************************************************
 * @attention
 * 云端隧道属于辅助功能；连接或认证失败时不应触发核心业务的整机复位。
 ******************************************************************************
 * @details
 * 本头文件仅公开客户端启动和状态输出接口。
 * 设备的业务 IP 保持不变，客户端最多维护三条独立 TLS 工作连接以桥接本机 Web 服务。
 ******************************************************************************
 */

#ifndef CMU_CLOUD_CLIENT_H
#define CMU_CLOUD_CLIENT_H
#include <stdbool.h>

/**
 * @brief  初始化云端适配并按产品配置启动后台客户端任务。
 * @return 配置无效而安全禁用云功能，或任务创建成功时返回 true；任务创建失败时返回 false。
 */
bool cloudClientStart(void);

/**
 * @brief  输出云端客户端的连接状态、公开端点和内存统计。
 * @details 日志不输出 token、认证字段或工作会话正文。
 */
void cloudClientShow(void);

#endif /* CMU_CLOUD_CLIENT_H */
